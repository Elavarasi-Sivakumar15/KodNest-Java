public class BooleanExp {
    public static void main(String[] args) {
        int solvedProblems = 22;
        int reachedProblems = 20;
        boolean targetReached = solvedProblems >= reachedProblems;
        System.out.println("Solved problems:" + solvedProblems);
        System.out.println("Reached problems:" + reachedProblems);
        System.out.println("Target reached:" + targetReached);               
    }
}
